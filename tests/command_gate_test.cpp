#include "command_gate.h"
#include <iostream>

int main() {
    unsigned checks=0,failed=0;
    auto check=[&](bool value,const char* message){++checks;if(!value){++failed;std::cerr<<"FAIL "<<message<<'\n';}};
    azsg::CommandGate gate;
    using Source=azsg::CommandSource;
    check(gate.accept("SG1|100|1|1000|500|1",Source::console,1000,0)==500u,"console request accepted");
    check(!gate.accept("SG1|100|1|1000|100|1",Source::file,1001,1000),"same sequence different value rejected");
    check(gate.accept("SG1|100|3|1001|200|1",Source::console,1001,1000)==200u,"new sequence accepted");
    check(!gate.accept("SG1|100|2|1000|500|1",Source::file,1002,2000),"delayed old file ignored");
    check(!gate.accept("invalid",Source::file,1002,2000),"invalid text ignored");
    check(!gate.accept("SG1|100|4|900|500|1",Source::file,1002,2000),"stale new sequence ignored");
    check(!gate.expire(8999),"invalid/stale data does not reset speed prematurely");
    check(gate.expire(9001),"invalid/replayed files cannot starve watchdog");
    check(!gate.expire(20000),"expiry emitted once");
    check(!gate.accept("SG1|100|3|1001|200|1",Source::console,1020,20000),"expired replay cannot restart");
    check(gate.accept("SG1|100|5|1020|25|1",Source::file,1020,20000)==25u,"fresh file fallback recovers");
    gate.accept("SG1|100|5|1020|25|1",Source::file,1027,27000);
    check(gate.expire(28001),"file duplicate is not a pulse");
    check(gate.accept("SG1|200|1|1030|300|1",Source::console,1030,30000)==300u,"new Lua session accepted");
    check(!gate.accept("SG1|100|6|1030|25|1",Source::file,1030,30001),"retired session cannot undo current request");
    gate.accept("SG1|200|1|1030|300|1",Source::console,1037,37000);
    check(!gate.expire(38001),"live exact query refreshes heartbeat without dirtying config");
    gate.accept("SG1|200|1|1030|500|1",Source::console,1038,38000);
    gate.accept("SG1|200|1|1030|300|1",Source::console,1044,44000);
    check(gate.expire(45001),"modified or stale exact console query cannot refresh heartbeat");
    check(std::string(gate.transport(45001))=="stale","expired status is not a connected channel");
    check(gate.heartbeat_age(45001)==8001u,"heartbeat age uses real elapsed milliseconds");
    azsg::CommandGate health;
    check(std::string(health.transport(0))=="waiting" && !health.console_healthy(0),"startup capture is not evidence of a console receipt");
    check(!health.heartbeat_age(0),"no heartbeat age before a receipt");
    health.accept("SG1|3|1|100|200|1",Source::console,100,0);
    check(health.console_healthy(2500) && std::string(health.transport(2500))=="console","validated console receipt grants bounded health");
    check(!health.console_healthy(2501) && std::string(health.transport(2501))=="degraded","lost console pulses degrade before watchdog expiry");
    health.accept("SG1|3|1|100|200|1",Source::file,102,2600);
    check(!health.console_healthy(2600),"duplicate file cannot refresh console health");
    health.accept("SG1|3|2|103|300|1",Source::file,103,3000);
    check(std::string(health.transport(3000))=="file" && !health.console_healthy(3000),"new file receipt records actual fallback");
    health.accept("SG1|3|2|103|300|1",Source::console,103,3100);
    check(health.console_healthy(3100),"matching console echo recovers immediate channel");
    health.accept("SG1|3|1|100|200|1",Source::console,104,6000);
    check(!health.console_healthy(6000),"old sequence cannot refresh health");
    azsg::FallbackPoller polling;
    check(polling.due(0,false) && !polling.due(99,false) && polling.due(100,false),"unconfirmed channel polls every 100ms");
    check(!polling.due(1099,true) && polling.due(1100,true),"healthy console polls fallback once per second");
    check(polling.due(1200,false),"console degradation immediately restores fast fallback polling");
    check(polling.due(100,false),"backward clock cannot starve the file poller");
    azsg::FallbackPoller healthy_polling;
    unsigned healthy_reads=0;
    for(std::uint64_t now=0;now<30000;now+=100) if(healthy_polling.due(now,true)) ++healthy_reads;
    check(healthy_reads==30,"healthy channel reduces 30s file scans from 300 to 30");
    azsg::CommandGate handoff;
    handoff.accept("SG1|4|1|1000|25|1",Source::console,1000,0);
    check(!handoff.accept("SG1|4|1|1000|25|1",Source::file,1004,4000),"first exact echo changes transport without reapplying rate");
    check(std::string(handoff.transport(4000))=="file" && handoff.heartbeat_age(4000)==0u,"one fresh file echo bridges slow-speed console loss");
    handoff.accept("SG1|4|1|1000|25|1",Source::file,1007,7000);
    check(handoff.heartbeat_age(7000)==3000u,"second file echo cannot extend the bounded handoff");
    check(!handoff.expire(8001),"handoff avoids transient 1x before the next slow file flush");
    check(handoff.accept("SG1|4|2|1005|25|1",Source::file,1009,9000)==25u,"next slow-speed file payload arrives without watchdog oscillation");
    handoff.accept("SG1|4|2|1005|25|1",Source::file,1012,12000);
    check(handoff.expire(17001),"file echoes cannot indefinitely renew a dead addon");
    check(azsg::console_command("INFO console: CVar \"AZSSpeedGearCommand\" is \"SG1|1|2|3|100|0\"\r")=="SG1|1|2|3|100|0","actual console log grammar");
    check(azsg::console_command("console: CVar \"azsspeedgearcommand\" is \"SG1|1|2|3|100|1\"").has_value(),"CVar case-insensitive");
    check(!azsg::console_command("console: CVar \"other\" is \"SG1|1|2|3|500|1\""),"other log not a command");
    check(!azsg::console_command("console: CVar \"AZSSpeedGearCommandSuffix\" is \"SG1|1|2|3|500|1\""),"exact CVar required");
    check(!azsg::console_command("console: CVar \"AZSSpeedGearCommand\" is \"SG1|1|2|3|500|1junk\""),"strict payload required");
    std::cout<<checks<<" checks, "<<failed<<" failures\n";
    return failed?1:0;
}
